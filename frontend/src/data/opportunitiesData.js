/**
 * Match a candidate's actual extracted skills against the opportunity dataset.
 *
 * @param {
 *   userSkills: Array<string | { canonical_name: string }>,
 *   district?: string,
 *   userExperienceYears?: number
 * } params
 * @returns {Array<object>} Ranked matched opportunities
 */
export function matchUserOpportunities({
  userSkills = [],
  district = 'all',
  userExperienceYears = 2,
} = {}) {
  // Extract normalized canonical string names
  const skillNames = (userSkills || []).map((s) =>
    typeof s === 'string' ? s.trim() : s?.canonical_name?.trim() || ''
  ).filter(Boolean);

  const userSkillsSet = new Set(skillNames.map((s) => s.toLowerCase()));

  const matchedOpps = ALL_OPPORTUNITIES.map((opp) => {
    const reqSkills = opp.required_skills || [];
    const matched = [];
    const missing = [];

    for (const req of reqSkills) {
      if (userSkillsSet.has(req.toLowerCase())) {
        matched.push(req);
      } else {
        missing.push(req);
      }
    }

    const totalReq = Math.max(reqSkills.length, 1);
    const rawScore = matched.length / totalReq;
    const matchScore = Math.round(rawScore * 100) / 100;

    let whyMatched = '';
    if (matched.length > 0) {
      const topMatchedStr = matched.slice(0, 3).join(', ');
      whyMatched = `Your verified skills in ${topMatchedStr} directly satisfy ${matched.length} of ${totalReq} core skill requirements for this role.`;
    } else {
      whyMatched = `Entry pathway for ${opp.title}; foundational training supported for this role.`;
    }

    const isDistMatch =
      district === 'all' ||
      (opp.district || '').toLowerCase().includes(district.toLowerCase()) ||
      (opp.location || '').toLowerCase().includes(district.toLowerCase());

    const distScore = isDistMatch ? 0.96 : 0.75;
    const expScore = Math.min(0.70 + (Math.min(userExperienceYears || 1, 5) / 5) * 0.25, 0.98);

    const breakdown = {
      skill_similarity: matchScore,
      experience_match: Math.round(expScore * 100) / 100,
      district_eligibility: distScore,
      eligibility_score: matchScore >= 0.33 ? 1.0 : 0.6,
    };

    const eligibilityStr =
      matchScore >= 0.66
        ? 'High Match (Verified)'
        : matchScore >= 0.33
        ? 'Eligible (Partial Match)'
        : 'Upskilling Recommended';

    return {
      ...opp,
      match_score: matchScore,
      eligibility: eligibilityStr,
      is_eligible: matchScore >= 0.25,
      matched_skills: matched,
      missing_skills: missing,
      why_matched: whyMatched,
      breakdown,
    };
  });

  // Filter by district if requested
  const filtered =
    district === 'all'
      ? matchedOpps
      : matchedOpps.filter(
          (o) =>
            (o.district || '').toLowerCase().includes(district.toLowerCase()) ||
            (o.location || '').toLowerCase().includes(district.toLowerCase())
        );

  // Rank by match_score descending, then by matched skill count descending
  return filtered.sort((a, b) => {
    if (b.match_score !== a.match_score) {
      return b.match_score - a.match_score;
    }
    return b.matched_skills.length - a.matched_skills.length;
  });
}

/**
 * Generate a dynamic skill gap analysis based on user skills and target role.
 */
export function generateSkillGap(userSkills = [], targetOpp = null) {
  const skillNames = (userSkills || []).map((s) =>
    typeof s === 'string' ? s.trim() : s?.canonical_name?.trim() || ''
  ).filter(Boolean);

  const role = targetOpp?.title || 'Target Technical Role';
  const reqSkills = targetOpp?.required_skills || ['Python', 'SQL', 'Git', 'Docker'];

  const currentSkillsSet = new Set(skillNames.map((s) => s.toLowerCase()));
  const currentSkills = skillNames;

  const gapSkills = reqSkills
    .filter((req) => !currentSkillsSet.has(req.toLowerCase()))
    .map((skill, idx) => ({
      skill,
      priority: idx === 0 ? 'high' : idx === 1 ? 'medium' : 'low',
      estimated_hours: 20 + idx * 15,
      reason: `Required for ${role} technical responsibilities and project delivery.`,
    }));

  const totalReq = Math.max(reqSkills.length, 1);
  const matchedCount = reqSkills.filter((r) => currentSkillsSet.has(r.toLowerCase())).length;
  const readiness = Math.round((matchedCount / totalReq) * 100) / 100;

  return {
    target_role: role,
    current_skills: currentSkills,
    required_skills: reqSkills,
    gap_skills: gapSkills.length > 0 ? gapSkills : [
      {
        skill: 'Advanced System Architecture',
        priority: 'low',
        estimated_hours: 30,
        reason: 'Recommended for senior advancement.',
      }
    ],
    readiness_score: Math.max(readiness, 0.4),
  };
}

